List<LocalFoodItem> searchLocalFoods(String query) {
  if (query.isEmpty) return [];
  final q = query.toLowerCase();
  return usFoodDatabase
      .where((item) =>
          item.name.toLowerCase().contains(q) ||
          (item.brand?.toLowerCase().contains(q) ?? false))
      .toList();
}

